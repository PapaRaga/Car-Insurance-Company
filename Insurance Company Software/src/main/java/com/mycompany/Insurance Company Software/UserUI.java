    private void addPolTextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addPolTextActionPerformed
        // TODO add your handling code here:
        try{

            String policyHoldName = polText1.getText();
            int policyID = Integer.parseInt(polID1.getText());
            String carModel = cmText1.getText();
            int manufacturingYear = Integer.parseInt(myText1.getText());
            double price = Double.parseDouble(pText1.getText());
            CarType carType = CarType.valueOf(ctCombo1.getSelectedItem().toString().toUpperCase());
            Car newCar = new Car(carModel, manufacturingYear, price, carType);
            int numberOfClaims = Integer.parseInt(nocText1.getText());
            int day = Integer.parseInt(dText.getText());
            int month = Integer.parseInt(mText.getText());
            int year = Integer.parseInt(yText.getText());
            MyDate newDate = new MyDate(year, month, day);
            InsurancePolicy ip;
            
            if(tppButton.isSelected()){
                
                String comment = cText.getText();
                ip = new ThirdPartyPolicy(policyHoldName, policyID, newCar, numberOfClaims, newDate, comment);
                
            }else{
                
                int driverAge = Integer.parseInt(cText.getText());
                int level = Integer.parseInt(lvlText.getText());
                ip = new ComprehensivePolicy(policyHoldName, policyID, newCar, numberOfClaims, newDate, driverAge, level);
                
            }
            
            if(user.addPolicy(ip, user.getName(), user.getPassword())){
                
                JOptionPane.showMessageDialog(this, "Policy has been added successfully!");
                polText1.setText("");
                polID1.setText("");
                cmText1.setText("");
                myText1.setText("");
                pText1.setText("");
                nocText1.setText("");
                dText.setText("");
                mText.setText("");
                yText.setText("");
                cText.setText("");
                lvlText.setText("");
                
            }else{
                
                JOptionPane.showMessageDialog(this, "Policy has not been added successfully!");
                
            }

        }
             
        catch(PolicyException e){
            
            JOptionPane.showMessageDialog(this, "You have not entered the right pattern for a policy ID (for example: 3XXXXXX)");
            
        }
        
        catch(PolicyHolderNameException e){
            
            JOptionPane.showMessageDialog(this, "You have not entered the right pattern for a policy holder name (for example: John Wick)");
            
        }
        
        catch(Exception e){
            
            JOptionPane.showMessageDialog(this, "A field may be empty or you have entered a string where it asks for an integer!");
             
        }
        
        
    }//GEN-LAST:event_addPolTextActionPerformed

