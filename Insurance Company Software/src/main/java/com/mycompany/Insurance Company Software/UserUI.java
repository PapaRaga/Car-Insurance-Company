    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        // TODO add your handling code here:
        int ind = policyTable.getSelectedRow();
        
        if(ind >= 0){
            
            Object policyIDvalue = policyTable.getValueAt(ind, 1);
            
            if(policyIDvalue != null){
                
                int policyIDRetrived = Integer.parseInt(policyIDvalue.toString());

                HashMap<Integer, InsurancePolicy> policies = user.getPolicies();
                InsurancePolicy policyToRemove = user.getPolicies().get(policyIDRetrived);
                
                if(policyToRemove != null){
                    
                    policies.remove(policyIDRetrived);
                    fillTable();
                    
                }else{
                    
                    JOptionPane.showMessageDialog(this, "Cannot delete a policy that does not exist!");
                    
                }
                
            }else{
                
                JOptionPane.showMessageDialog(this, "Cannot delete a policy that does not exist!");
                
            }
            
        }
    }//GEN-LAST:event_deleteButtonActionPerformed

