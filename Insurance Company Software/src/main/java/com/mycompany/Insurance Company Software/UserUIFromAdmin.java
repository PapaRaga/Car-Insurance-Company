    public void fillTable(){
        
        String[] header = {"Policy Holder Name","Policy ID","Car Model","Manufacturing Year","Price","Car Type","Number of Claims","Expiry Date","Comment","Driver Age","Level","Price for Policy"};
        DefaultTableModel model = new DefaultTableModel(header,0);
        policyTable.setModel(model);
        
        for(InsurancePolicy ip: user.getPolicies().values()){
            
            String[] row = new String[12];
            row[0] = ip.getPolicyHolderName();
            row[1] = ip.getID() + "";
            row[2] = ip.getCar().getModel();
            row[3] = ip.getCar().getManufacturingYear() + "";
            row[4] = ip.getCar().getPrice() + "";
            row[5] = ip.getCar().getType() + "";
            row[6] = ip.getNumberOfClaims() + "";
            row[7] = ip.getExpiryDate().toString();
            
            if(ip instanceof ThirdPartyPolicy){
                
                row[8] = ((ThirdPartyPolicy)ip).comments;
                row[9] = "NA";
                row[10] = "NA";
                
            }else{
                
                row[8] = "NA";
                row[9] = ((ComprehensivePolicy)ip).driverAge + "";
                row[10] = ((ComprehensivePolicy)ip).level + "";
                
            }
            
            row[11] = String.format("$%.2f", ip.calcPay(500));
            model.addRow(row);
            
        }
        
    }
    
